export type HiddenByCanonical = Record<string, string[]>;

function row(canonical: string, aliases: readonly string[]): [string, string[]] {
  return [canonical, [...aliases]];
}

function pack(rows: Array<[string, string[]]>): HiddenByCanonical {
  const out: HiddenByCanonical = {};
  for (const [canon, aliases] of rows) out[canon] = aliases;
  return out;
}

