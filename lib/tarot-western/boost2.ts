import { wg, type WesternGroup } from "./types";

type Boost = {
  groups: WesternGroup[];
  tabs: Array<{ id: string; label: string; groupLabels: readonly string[] }>;
};

function b(
  tabs: Boost["tabs"],
  groups: WesternGroup[],
): Boost {
  return { tabs, groups };
}

