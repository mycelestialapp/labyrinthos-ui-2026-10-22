function pack(rows: Array<[string, string[]]>): HiddenByCanonical {
  const out: HiddenByCanonical = {};
  for (const [canon, aliases] of rows) out[canon] = aliases;
  return out;
}

function more(canon: string, shorts: string[]): [string, string[]] {
  const extra: string[] = [];
  for (const s of shorts) {
    const t = s.trim();
    if (!t) continue;
    extra.push(t.endsWith("？") || t.endsWith("?") ? t : `${t}？`);
  }
  return [canon, extra];
}

