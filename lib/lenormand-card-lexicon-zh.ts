export const SHADOW_CARD_IDS = new Set([6, 7, 8, 10, 11, 14, 21, 23, 36]);

export function categoryToDomain(category: QuestionCategory): LenormandDomainId {
  switch (category) {
    case "感情婚姻":
      return "love";
    case "事业工作":
      return "career";
    case "财运投资":
      return "money";
    case "学业考试":
      return "study";
    case "身体健康":
      return "health";
    case "人际关系":
      return "relation";
    case "出行迁居":
      return "travel";
    case "官司法律":
      return "legal";
    case "生育子女":
      return "child";
    case "失物寻找":
      return "lost";
    case "选择决策":
      return "choice";
    case "占梦境":
      return "spirit";
    case "宠物":
      return "pet";
    case "心理疏导":
      return "spirit";
    case "人生建议":
      return "other";
    case "灵性成长":
      return "spirit";
    case "占风水":
      return "feng";
    case "代人问卜":
      return "relation";
    default:
      return "other";
  }
}

