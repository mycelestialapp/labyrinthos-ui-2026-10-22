/**
 * 走失的动物：按寻找读，不按绝育/看病读。
 * 正统雷诺曼把走失当「谁/在哪/还能不能回来」，方向落在现场。
 */
import { normalizeQuestionTextZh } from "./question-text-normalize-zh";

const PET_TOKEN = /狗|猫|貓|宠物|寵物|毛孩子|主子/;
const LOST_TOKEN = /走丢|走失|丢了|丟了|找回|找回来|找回來|往哪找|哪个方向|哪個方向/;

export function isLostPetInquiry(question: string): boolean {
  const q = normalizeQuestionTextZh(question || "");
  return PET_TOKEN.test(q) && LOST_TOKEN.test(q);
}

