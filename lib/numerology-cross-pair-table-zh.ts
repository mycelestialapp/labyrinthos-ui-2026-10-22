function withCrossVoiceTail(cell: CrossPairCellZh): CrossPairCellZh {
  return {
    ...cell,
    unfold: cell.unfold + NUMEROLOGY_VOICE_TAIL_CROSS_UNFOLD_ZH,
  };
}

/** 主路径与个人年须原数查表（1–9 或 11/22/33）；异常数字回退到 9-9 */
export function numerologyCrossPairTableLookupZh(lifePath: number, personalYear: number): CrossPairCellZh {
  const k = `${lifePath}-${personalYear}`;
  const hit = NUMEROLOGY_CROSS_PAIR_TABLE_ZH[k];
  if (hit) return withCrossVoiceTail(hit);
  const lp = lifePath >= 1 && lifePath <= 33 ? ((lifePath - 1) % 9) + 1 : 9;
  const py = personalYear >= 1 && personalYear <= 33 ? ((personalYear - 1) % 9) + 1 : 9;
  const fb = NUMEROLOGY_CROSS_PAIR_TABLE_ZH[`${lp}-${py}`] ?? NUMEROLOGY_CROSS_PAIR_TABLE_ZH["9-9"]!;
  return withCrossVoiceTail(fb);
}
