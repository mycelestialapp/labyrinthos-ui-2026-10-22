/** 大师数行/列：在对应基底格上叠注，避免把 11 误当 2、把 22 误当 4 去读同一套字 */
function seedMasterPairRows() {
  const masters = [11, 22, 33] as const;
  const baseLp = { 11: 2, 22: 4, 33: 6 } as const;
  const basePy = { 11: 2, 22: 4, 33: 6 } as const;

  for (const mlp of masters) {
    const blp = baseLp[mlp];
    for (let py = 1; py <= 9; py++) {
      const b = NUMEROLOGY_CROSS_PAIR_TABLE_ZH[`${blp}-${py}`]!;
      NUMEROLOGY_CROSS_PAIR_TABLE_ZH[`${mlp}-${py}`] = {
        thesis: b.thesis,
        unfold: `（主路径为大师数 ${mlp}：在 ${blp} 路底色上读，直觉与峰值段会抬高；下列场面仍按「${blp}×${py}」基底理解，再叠大师体感。）${b.unfold}`,
        taboo: b.taboo,
        advice: b.advice,
      };
    }
  }
  for (const mpy of masters) {
    const bpy = basePy[mpy];
    for (let lp = 1; lp <= 9; lp++) {
      const b = NUMEROLOGY_CROSS_PAIR_TABLE_ZH[`${lp}-${bpy}`]!;
      NUMEROLOGY_CROSS_PAIR_TABLE_ZH[`${lp}-${mpy}`] = {
        thesis: b.thesis,
        unfold: `（个人年为大师数 ${mpy}：含 ${bpy} 之年节律，外缘与绪波更密；下文在「${lp}×${bpy}」基底上再叠一层。）${b.unfold}`,
        taboo: b.taboo,
        advice: b.advice,
      };
    }
  }
  for (const mlp of masters) {
    const blp = baseLp[mlp];
    for (const mpy of masters) {
      const bpy = basePy[mpy];
      const b = NUMEROLOGY_CROSS_PAIR_TABLE_ZH[`${blp}-${bpy}`]!;
      NUMEROLOGY_CROSS_PAIR_TABLE_ZH[`${mlp}-${mpy}`] = {
        thesis: b.thesis,
        unfold: `（主路径 ${mlp}、个人年 ${mpy}：双大师叠幅，宜缓宜简；先按 ${blp}×${bpy} 基底读，再收束承诺面。）${b.unfold}`,
        taboo: b.taboo,
        advice: b.advice,
      };
    }
  }
}

