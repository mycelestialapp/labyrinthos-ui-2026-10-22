function pickBd(n: number): NumeralTwinLayerZh {
  if (BD[n]) return BD[n];
  return BD[reduceLikeDay(n)];
}

function reduceLikeDay(n: number): number {
  if (n === 11 || n === 22) return n;
  let v = n;
  while (v > 9) {
    let s = 0;
    let x = Math.abs(Math.floor(v));
    while (x > 0) {
      s += x % 10;
      x = Math.floor(x / 10);
    }
    v = s;
    if (v === 11 || v === 22) return v;
  }
  return v >= 1 && v <= 9 ? v : 9;
}

