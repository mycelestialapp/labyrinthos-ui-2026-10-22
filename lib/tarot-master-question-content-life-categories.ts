export interface LifeQuestionFiveModules {
  cardSpeaking: string;
  psychologyLayer: string;
  spiritLayer: string;
  actionPath: string;
  masterSummary: string;
}

const STORE = new Map<string, LifeQuestionFiveModules>();

function key(categoryId: string, questionText: string): string {
  return `${categoryId}\0${questionText.trim()}`;
}

function register(categoryId: string, questionText: string, m: LifeQuestionFiveModules): void {
  STORE.set(key(categoryId, questionText), m);
}

export function getLifeQuestionFiveModules(
  categoryId: string,
  questionText: string
): LifeQuestionFiveModules | null {
  const q = questionText?.trim() ?? '';
  if (!q) return null;
  return STORE.get(key(categoryId, q)) ?? null;
}

