type Rot5 = [string, string, string, string, string];

function rot5(block: Rot5, i: number): string {
  return block[i % 5];
}

function buildCategory(
  categoryId: LifeCategoryId,
  questions: readonly string[],
  hooks: readonly string[],
  psych: Rot5,
  spirit: Rot5,
  action: Rot5,
  summary: Rot5
): void {
  questions.forEach((q, i) => {
    register(categoryId, q, {
      cardSpeaking: `你问的是「${q}」\n\n${hooks[i] ?? hooks[0]}`,
      psychologyLayer: rot5(psych, i),
      spiritLayer: rot5(spirit, i),
      actionPath: rot5(action, i),
      masterSummary: rot5(summary, i),
    });
  });
}

