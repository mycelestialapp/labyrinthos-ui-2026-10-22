export function mergeDisplayQuestions(base: readonly string[], extras: string[] = []): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const q of [...extras, ...base]) {
    if (!q || seen.has(q)) continue;
    seen.add(q);
    out.push(q);
  }
  return out;
}
