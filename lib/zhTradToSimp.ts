export function tradToSimp(text: string): string {
  let out = text;
  for (const [from, to] of PHRASE_MAP) {
    out = out.split(from).join(to);
  }
  return Array.from(out)
    .map(ch => CHAR_MAP[ch] ?? ch)
    .join('');
}
