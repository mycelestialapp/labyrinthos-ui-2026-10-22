function pickGrid(a, b, id) {
  const la = a.length;
  const lb = b.length;
  const t = id % (la * lb);
  return [Math.floor(t / lb), t % lb];
}

/** id∈0..111 与 (id%11,id%13) 在 11×13 互质格上一一对应，短句组合 112 种不重复 */
function crtLine(a11, b13, id) {
  return a11[id % 11] + b13[id % 13];
}

/** 用花色/点数/正逆打散抽取，降低「同 id 池」造成的句段撞车 */
function cardSkew(suit, num, up, id) {
  return mix32(
    id * 0x9e3779b1 +
      suitIdx(suit) * 0xb5297a4d +
      num * 0x8dc4e4c1 +
      (up ? 0x4f1bbcdc : 0x7ed55e11),
  );
}

function pickSkewed(arr, suit, num, up, id, salt) {
  const h = mix32(cardSkew(suit, num, up, id) + salt * 0x165667b1);
  return arr[h % arr.length];
}

function pick3Skewed(arr, suit, num, up, id, s0, s1, s2) {
  return [
    pickSkewed(arr, suit, num, up, id, s0),
    pickSkewed(arr, suit, num, up, id, s1),
    pickSkewed(arr, suit, num, up, id, s2),
  ];
}

