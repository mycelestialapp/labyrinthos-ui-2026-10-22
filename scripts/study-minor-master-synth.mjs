/** 自检：112 条各层是否两两不同（Q2/Q3 分别测） */
export function selfCheckUniqueness(synthFn, label) {
  const keys = ["psychologyLayer", "spiritLayer", "actionPath", "masterSummary", "cardSpeaking"];
  const sets = Object.fromEntries(keys.map((k) => [k, new Set()]));
  for (const suit of ["wands", "cups", "swords", "pentacles"]) {
    for (let num = 1; num <= 14; num++) {
      for (const up of [true, false]) {
        const row = synthFn(suit, num, up);
        for (const k of keys) sets[k].add(row[k]);
      }
    }
  }
  let allOk = true;
  for (const k of keys) {
    const ok = sets[k].size === 112;
    if (!ok) allOk = false;
    console.error(`[${label}] ${k} unique: ${sets[k].size}/112 ${ok ? "OK" : "COLLISION"}`);
  }
  return allOk;
}
