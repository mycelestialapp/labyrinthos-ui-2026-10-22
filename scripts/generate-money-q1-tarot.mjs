function minorCardSpeaking(suit, num, up) {
  const sz = suitZh[suit];
  const rk = rankName(num);
  const u = up ? '正位' : '逆位';
  const fire = suit === 'wands';
  const water = suit === 'cups';
  const air = suit === 'swords';
  let hook = '';
  if (fire) {
    hook = up
      ? '火在催你行动：别再用倒卡当节奏，先把「何时、与谁说」点起来。'
      : '火逆：急躁会骂自己或骂家人，反而谈崩。先降温再开口。';
  } else if (water) {
    hook = up
      ? '水在问情绪：你怕的是数字，还是怕他们眼里的失望？先把泪与话分开。'
      : '水逆：委屈与内疚会糊住事实，练习只报三期数字与请求。';
  } else if (air) {
    hook = up
      ? '风要清晰：列三句台词——事实、请求、下一步。刀口向内是自责，向外是方案。'
      : '风逆：越解释越乱，越吵越离题。写纸上念，比现场编安全。';
  } else {
    hook = up
      ? '土要落地：表格、日期、金额，比「我很惨」更能换来帮助。'
      : '土逆：拖延整理只会拖延开口。今天只填一格表也是赢。';
  }
  const nHook =
    num === 1
      ? up
        ? '王牌像第一簇火：承认「还不上了」就是新起点。'
        : '王牌逆：别用新卡盖旧洞，开口前先停借。'
      : num <= 3
        ? up
          ? '早期数字：越早同步，越早止损。'
          : '早期逆：别把小瞒养成大谎。'
        : num <= 7
          ? up
            ? '中段：该定「告知日」了，不要再「下个月再说」。'
            : '中段逆：躲电话只会让铃声更像鞭子。'
          : num <= 10
            ? up
              ? '压力顶格：更需要具体方案，而不是情绪倾泻。'
              : '顶格逆：崩溃式坦白会吓到人，分段说。'
            : num === 11
              ? up
                ? '侍从：第一次说很难，像小孩学话——允许结巴。'
                : '侍从逆：别用撒娇或发脾气代替数字。'
              : num === 12
                ? up
                  ? '骑士：定一天去说，像出征——带表不带刀。'
                  : '骑士逆：别冲动发誓「马上还清」，说到做不到更伤信。'
                : num === 13
                  ? up
                    ? '王后：温柔而清楚，家里需要你的稳，也需要你的真。'
                    : '王后逆：别情绪勒索「你们都不懂我」，要说「我需要」。'
                  : up
                    ? '国王：扛责的样子是带方案开口，不是只倒苦水。'
                    : '国王逆：别在家里装权威硬撑，示弱有时是领导。';
  return `${sz}${rk}${u}落在这题上：${hook}${nHook}`;
}

function seedFrom(id, up) {
  let h = 0;
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) | 0;
  return h + (up ? 17 : 0);
}

