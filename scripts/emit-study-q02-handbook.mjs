function stripActBaggageLine(s) {
  return s
    .replace(/\\n\\n检查你的「行囊」：/g, "\\n\\n【行囊自检】")
    .replace(/\n\n检查你的「行囊」：/g, "\n\n【行囊自检】");
}
function wrapQ2Act(s) {
  const x = stripActBaggageLine(s);
  if (x.startsWith("【转专业·今日一格】")) return x;
  return `【转专业·今日一格】${x}`;
}
function wrapQ2Sum(s) {
  if (s.startsWith("【转专业·总断】")) return s;
  return `【转专业·总断】${s}`;
}

