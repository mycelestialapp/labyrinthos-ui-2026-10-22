function rankName(n) {
  if (n === 1) return '王牌';
  if (n <= 10) return ['', '一', '二', '三', '四', '五', '六', '七', '八', '九', '十'][n];
  if (n === 11) return '侍从';
  if (n === 12) return '骑士';
  if (n === 13) return '王后';
  if (n === 14) return '国王';
  return String(n);
}

function labelForSlot(slot) {
  if (slot < 44) {
    const mi = Math.floor(slot / 2);
    const up = slot % 2 === 0;
    return `${majors[mi]}${up ? '正位' : '逆位'}`;
  }
  const rest = slot - 44;
  const si = Math.floor(rest / 28);
  const r = rest % 28;
  const rank = Math.floor(r / 2) + 1;
  const up = r % 2 === 0;
  const sz = suitZh[suits[si]];
  return `${sz}${rankName(rank)}${up ? '正位' : '逆位'}`;
}

