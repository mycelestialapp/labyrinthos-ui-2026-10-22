function buildPsych(qi, slot, k) {
  const q = Q[qi];
  const band = Q_BAND[qi] ?? '学业';
  const lab = labelForSlot(slot);
  const n = N[k % N.length];
  const v = V[Math.floor(k / 60) % V.length];
  const m = MIND[(k * 3) % MIND.length];
  const r = ROOT[(k * 5) % ROOT.length];
  return (
    `【${band}·现状】${TAG_PSYCH[qi]}\n\n` +
    `【${band}·心事】你拎着「${q}」时，${lab}把心里的${n}与${v}推到台前——${m}\n\n` +
    `【${band}·根源】${r}`
  );
}

function buildSpirit(qi, k) {
  const band = Q_BAND[qi] ?? '学业';
  const tag = TAG_SPIRIT[qi];
  const lead = SPIRIT_LEAD[k % SPIRIT_LEAD.length];
  const core = SPIRIT_CORE[(k * 7) % SPIRIT_CORE.length];
  const f = k % 8;
  if (f === 0) return `【${band}·读本】${tag}\n\n【${band}·示意】${lead}\n\n【${band}·记取】${core}`;
  if (f === 1) return `判读落在此题：${tag}\n\n${lead}\n\n你可收束为一步：${core}`;
  if (f === 2) return `【${band}·牌层】${tag}\n\n${lead}\n\n【${band}·脚层】${core}`;
  if (f === 3) return `读本直陈：${tag}\n\n人事落实：${lead}\n\n行者记取：${core}`;
  if (f === 4) return `象示在此题：${tag}\n\n用以自处：${lead}\n\n落到实处：${core}`;
  if (f === 5) return `【${band}·判读】${tag}\n\n${lead}\n\n【${band}·收刃】${core}`;
  if (f === 6) return `灵识催你清醒：${tag}\n\n${lead}\n\n脚步只取一格：${core}`;
  return `象外一言：${tag}\n\n象内一行：${lead}\n\n同时记下：${core}`;
}

function buildAction(qi, k) {
  const band = Q_BAND[qi] ?? '学业';
  const a = ACT_A[k % ACT_A.length];
  const rawB = ACT_B[(k * 11) % ACT_B.length];
  const b = rawB.replace(/^检查你的「行囊」：/, '');
  return `【${band}·今日一格】今天，先把题拆成能落地的一步：${TAG_ACTION[qi]}\n\n${a}\n\n【行囊自检】${b}`;
}

function buildSum(qi, k) {
  const band = Q_BAND[qi] ?? '学业';
  const s1 = SUM[k % SUM.length];
  const s2 = SUM[(k * 13) % SUM.length];
  const mid = s1.endsWith('。') ? '' : '。';
  return `【${band}·总断】${s1}${mid}${s2}`;
}

