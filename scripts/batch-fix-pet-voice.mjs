import fs from "fs";
import path from "path";

/** 宠物域：感情残留 → 照护／兽医口吻（不翻判边） */
const dir = path.join(process.cwd(), "lib/tarot-western-reading");
const reps = [
  ["近完不想跳进", "上手完不想跳进"],
  ["近完下一秒", "上手完下一秒"],
  ["近完要收权", "上手完要收权"],
  ["近完一提", "上手完一提"],
  ["近完立刻空", "上手完立刻空"],
  ["近完算力气", "上手完算力气"],
  ["近完", "上手完"],
  ["亲近当碰", "体感当碰"],
  ["亲近当", "体感当"],
  ["亲近用来止渴", "开口用来止渴"],
  ["亲近可以发生", "靠近可以发生"],
  ["亲近", "体感"],
  ["不想被写成一对户", "不想被写成一份病例"],
  ["一对户", "一份病例"],
  ["清楚的一行对方还接得住", "清楚的一行窗口还接得住"],
  ["对方还接得住", "窗口还接得住"],
  ["关不是还差一次谈话", "关不是还差一次问诊"],
  ["欲望可以近，当家这件事你不做", "兴头可以有，当责这件事你不做"],
  ["欲望可以近", "兴头可以有"],
  ["又会要一句她给不出的回音", "又会要一句帘后给不出的回音"],
  ["她给不出的回音", "帘后给不出的回音"],
  ["进的不是诊室，是备用的观众席", "进的不是诊室，是旁听席"],
  ["进的不是身体，是备用的观众席", "进的不是诊室，是旁听席"],
  ["是备用的观众席", "是旁听席"],
  ["备用的观众席", "旁听席"],
  ["开场不是惦记。这句点进去，进的不是诊室，是旁听席", "开场不是惦着病名。这句点进去，进的不是诊室，是旁听席"],
  ["开场不是惦记", "开场不是惦着病名"],
  ["翻正这一下，查询先落地", "翻正这一下，额外账先落地"],
  ["查询先落地", "额外账先落地"],
  ["不把追问写成唤窗术", "不把追问写成催窗的法子"],
];

let files = 0;
let changes = 0;
for (const f of fs.readdirSync(dir)) {
  if (!/^pet-q\d+-\d+\.ts$/.test(f)) continue;
  const p = path.join(dir, f);
  let t = fs.readFileSync(p, "utf8");
  const orig = t;
  let n = 0;
  for (const [a, b] of reps) {
    const c = t.split(a).length - 1;
    if (c) {
      t = t.split(a).join(b);
      n += c;
    }
  }
  if (t !== orig) {
    fs.writeFileSync(p, t);
    files++;
    changes += n;
  }
}
console.log(JSON.stringify({ files, changes }));
