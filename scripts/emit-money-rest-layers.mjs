function buildPsych(qi, slot, k) {
  const q = Q[qi];
  const lab = labelForSlot(slot);
  const n = N[k % N.length];
  const v = V[Math.floor(k / 60) % V.length];
  const m = MIND[(k * 3) % MIND.length];
  const r = ROOT[(k * 5) % ROOT.length];
  return (
    `【钱题现状】${TAG_PSYCH[qi]}\n\n` +
    `【心理层面】你拎着「${q}」时，${lab}把心里的${n}与${v}推到台前——${m}\n\n` +
    `【根源层面】${r}`
  );
}

function buildSpirit(qi, k) {
  const tag = TAG_SPIRIT[qi];
  const raw = SPIRIT_CORPUS[(k * 31 + qi * 11) % SPIRIT_CORPUS.length];
  const coreMatch = raw.match(/\n\n核心(?:提醒|启示)：([\s\S]+)$/);
  if (coreMatch && coreMatch.index != null) {
    const lead = raw.slice(0, coreMatch.index).trim();
    const core = coreMatch[1].trim();
    return `宇宙在告诉你：${tag}\n\n${lead}\n\n核心启示：${core}`;
  }
  return `宇宙在告诉你：${tag}\n\n${raw.trim()}\n\n核心启示：${
    SPIRIT_INSIGHT_FALLBACK[(k * 37 + qi) % SPIRIT_INSIGHT_FALLBACK.length]
  }`;
}

function buildAction(qi, k) {
  const core = ACTION_CORPUS[(k * 37 + qi * 13) % ACTION_CORPUS.length];
  return `今天，先把题拆成能落地的一步：${TAG_ACTION[qi]}\n\n${core}`;
}

function buildSum(qi, k) {
  const combined = [...TAG_SUM, ...SUM_CORPUS];
  return combined[(k * 43 + qi * 31) % combined.length];
}

